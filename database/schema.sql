-- Esquema relacional del catálogo, usuarios y carrito.
CREATE TABLE IF NOT EXISTS Users (
 id INTEGER AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 role VARCHAR(255) NOT NULL DEFAULT 'customer'
);
CREATE TABLE IF NOT EXISTS Products (
 id INTEGER AUTO_INCREMENT PRIMARY KEY, name VARCHAR(255) NOT NULL,
 licence VARCHAR(255) NOT NULL, category VARCHAR(255) NOT NULL,
 sku VARCHAR(255) NOT NULL UNIQUE, price DECIMAL(12,2) NOT NULL,
 stock INTEGER NOT NULL, description TEXT NOT NULL,
 image VARCHAR(255) NOT NULL, box VARCHAR(255) NOT NULL,
 discount INTEGER NOT NULL DEFAULT 0, installments INTEGER NOT NULL DEFAULT 3,
 CHECK (price > 0), CHECK (stock >= 0), CHECK (discount BETWEEN 0 AND 90)
);
CREATE TABLE IF NOT EXISTS CartItems (
 id INTEGER AUTO_INCREMENT PRIMARY KEY, userId INTEGER NOT NULL,
 productId INTEGER NOT NULL, quantity INTEGER NOT NULL,
 UNIQUE KEY cart_user_product (userId,productId),
 FOREIGN KEY (userId) REFERENCES Users(id) ON DELETE CASCADE,
 FOREIGN KEY (productId) REFERENCES Products(id) ON DELETE CASCADE,
 CHECK (quantity > 0)
);
